package autogradesys.validation;

import java.io.IOException;
import java.nio.charset.Charset;
import java.nio.charset.MalformedInputException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Predicate;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import autogradesys.validation.ValidationEvent.Type;

/**
 * Makes sure every Java file in a student's folder names its author correctly at the top. If the
 * exam's header block is there, an empty or wrong Name / Email ID is set from the scoresheet (a name
 * that already holds every part of the registered name, in any order, is kept). If there is no
 * header at all, a block in the same format is added.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
public final class HeaderFixer {

    // How many lines at the top of a file count as its header.
    private static final int HEADER_LINES = 10;
    // Byte order mark some editors put at the start of a file; a comment must go after it.
    private static final String BOM = "\uFEFF";
    private static final String JAVA_EXTENSION = ".java";

    // The exam's header has "Name:" and "Email ID:" lines, e.g. " * Name: Teo Chee". Group 1 is the start of
    // the line up to the colon (kept as written) and group 2 is whatever the student typed after it.
    private static final Pattern NAME_LINE =
            Pattern.compile("(?im)^([ \\t]*(?:\\*+|//+)?[ \\t]*name[ \\t]*:)[ \\t]*(.*?)[ \\t]*$");
    private static final Pattern EMAIL_LINE =
            Pattern.compile("(?im)^([ \\t]*(?:\\*+|//+)?[ \\t]*email(?:[ \\t]*id)?[ \\t]*:)[ \\t]*(.*?)[ \\t]*$");
    // Matches the same lines whether or not they are filled in: it tells us the header block exists.
    private static final Pattern HEADER_LABEL =
            Pattern.compile("(?im)^[ \\t]*(?:\\*+|//+)?[ \\t]*(?:name|email(?:[ \\t]*id)?)[ \\t]*:");

    /**
     * Initializes the utility that repairs source headers for a known student.
     */
    private HeaderFixer() {
    }

    /**
     * @param label the prompt or display label.
     * @param studentDir the directory containing one student submission.
     * @param student the registered student identity.
     * @param allStudents the argument supplied to this operation.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    public static List<ValidationEvent> fixAll(String label, Path studentDir, Student student,
            List<Student> allStudents) {
        List<ValidationEvent> events = new ArrayList<>();
        List<Path> javaFiles;
        // Files.walk does not follow symbolic links, matching the preflight's safety rule.
        try (Stream<Path> walk = Files.walk(studentDir)) {
            javaFiles = walk
                    .filter(p -> p.toString().endsWith(JAVA_EXTENSION) && Files.isRegularFile(p, LinkOption.NOFOLLOW_LINKS))
                    .filter(p -> !SubmissionFiles.isJunk(studentDir.relativize(p)))
                    .sorted()
                    .toList();
        } catch (IOException e) {
            events.add(new ValidationEvent(label, Type.FIX_FAILED, nameOf(studentDir) + "/",
                    "could not list the Java files (" + e.getMessage() + ")"));
            return events;
        }

        for (Path file : javaFiles) {
            fixFile(label, studentDir, file, student, allStudents, events);
        }
        return events;
    }

    // Checks one file and adds the header if it is missing.
    /**
     * Repairs the header of one source file and records the changes made.
     * @param label the prompt or display label.
     * @param studentDir the directory containing one student submission.
     * @param file the file being validated or processed.
     * @param student the registered student identity.
     * @param allStudents the argument supplied to this operation.
     * @param events the argument supplied to this operation.
     */
    private static void fixFile(String label, Path studentDir, Path file, Student student,
            List<Student> allStudents, List<ValidationEvent> events) {
        String shownPath = nameOf(studentDir) + "/" + studentDir.relativize(file).toString().replace('\\', '/');
        try {
            // Read as UTF-8, or as ISO-8859-1 when the file is not valid UTF-8, and write back the same way.
            Charset charset = StandardCharsets.UTF_8;
            String content;
            try {
                content = Files.readString(file, charset);
            } catch (MalformedInputException e) {
                charset = StandardCharsets.ISO_8859_1;
                content = Files.readString(file, charset);
            }

            String head = content.substring(0, headerEnd(content));

            String other = findOtherStudent(head.toLowerCase(), student, allStudents);
            if (other != null) {
                // Not fixed: a header naming a different student is worth a human look.
                events.add(new ValidationEvent(label, Type.HEADER_FOREIGN, shownPath,
                        "the header names a different student: " + other));
            } else if (HEADER_LABEL.matcher(head).find()) {
                // The template's header block is there: fix its fields instead of adding a second block.
                FieldFix fix = correctFields(head, student);
                if (!fix.changes().isEmpty()) {
                    Files.writeString(file, fix.head() + content.substring(head.length()), charset);
                    events.add(new ValidationEvent(label, fix.overwrote() ? Type.HEADER_CORRECTED : Type.HEADER_ADDED,
                            shownPath, String.join("; ", fix.changes())));
                }
            } else if (!mentions(head.toLowerCase(), student)) {
                Files.writeString(file, withHeader(content, student), charset);
                events.add(new ValidationEvent(label, Type.HEADER_ADDED, shownPath,
                        "added a header with the name and email ID of " + student.username()));
            }
        } catch (IOException e) {
            events.add(new ValidationEvent(label, Type.FIX_FAILED, shownPath,
                    "could not check the header (" + e.getMessage() + ")"));
        }
    }

    // The username of a different registered student that appears in the header, or null.
    /**
     * Finds another registered student whose identity appears in the header.
     * @param header the argument supplied to this operation.
     * @param student the registered student identity.
     * @param allStudents the argument supplied to this operation.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static String findOtherStudent(String header, Student student, List<Student> allStudents) {
        for (Student other : allStudents) {
            if (!other.username().equalsIgnoreCase(student.username())
                    && header.contains(other.username().toLowerCase())) {
                return other.username();
            }
        }
        return null;
    }

    // True if the header holds the username, the email, or every part of the full name.
    /**
     * Reports whether a header contains identifying text for the student.
     * @param header the argument supplied to this operation.
     * @param student the registered student identity.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static boolean mentions(String header, Student student) {
        if (header.contains(student.username().toLowerCase())) {
            return true;
        }
        if (!student.email().isEmpty() && header.contains(student.email().toLowerCase())) {
            return true;
        }
        List<String> parts = nameParts(student);
        return !parts.isEmpty() && containsAll(header, parts);
    }

    // Where the header region (the first HEADER_LINES lines) ends in the content.
    /**
     * Returns the character position immediately after the source header.
     * @param content the argument supplied to this operation.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static int headerEnd(String content) {
        int end = 0;
        for (int line = 0; line < HEADER_LINES && end < content.length(); line++) {
            int newline = content.indexOf('\n', end);
            if (newline < 0) {
                return content.length();
            }
            end = newline + 1;
        }
        return end;
    }

    /** The header after correction, what was changed, and whether anything the student typed was replaced.
     * @param head the argument supplied to this operation.
     * @param changes the argument supplied to this operation.
     * @param overwrote the argument supplied to this operation.
     */
    private record FieldFix(String head, List<String> changes, boolean overwrote) {
    }

    // Sets Name and Email ID from the scoresheet wherever they are empty or do not match the student.
    /**
     * Corrects the recognized name, username, and email fields in a source header.
     * @param head the argument supplied to this operation.
     * @param student the registered student identity.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static FieldFix correctFields(String head, Student student) {
        List<String> changes = new ArrayList<>();
        String corrected = correctField(head, NAME_LINE, "Name", displayName(student),
                value -> nameAccepts(value, student), changes);
        corrected = correctField(corrected, EMAIL_LINE, "Email ID", student.username(),
                value -> value.toLowerCase().contains(student.username().toLowerCase()), changes);
        boolean overwrote = changes.stream().anyMatch(change -> change.startsWith("corrected"));
        return new FieldFix(corrected, changes, overwrote);
    }

    // Rewrites every line of this field whose value is empty or not accepted, keeping the line's own start.
    /**
     * Replaces one header field with the student’s registered value when needed.
     * @param head the argument supplied to this operation.
     * @param line the argument supplied to this operation.
     * @param field the argument supplied to this operation.
     * @param correct the argument supplied to this operation.
     * @param accepts the argument supplied to this operation.
     * @param changes the argument supplied to this operation.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static String correctField(String head, Pattern line, String field, String correct,
            Predicate<String> accepts, List<String> changes) {
        Matcher matcher = line.matcher(head);
        StringBuilder result = new StringBuilder();
        while (matcher.find()) {
            String value = matcher.group(2);
            // A value that runs into "*/" shares its line with the end of the comment, so leave it alone.
            boolean replace = !value.contains("*/") && !accepts.test(value);
            if (replace) {
                changes.add(value.isEmpty()
                        ? "filled in " + field + " '" + correct + "'"
                        : "corrected " + field + " from '" + value + "' to '" + correct + "'");
            }
            matcher.appendReplacement(result,
                    Matcher.quoteReplacement(replace ? matcher.group(1) + " " + correct : matcher.group()));
        }
        matcher.appendTail(result);
        return result.toString();
    }

    // A name is accepted if it is not empty and holds every part of the registered name, in any order.
    /**
     * Reports whether a header name is an accepted form of the student name.
     * @param value the value to quote or convert.
     * @param student the registered student identity.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static boolean nameAccepts(String value, Student student) {
        return !value.isEmpty() && containsAll(value.toLowerCase(), nameParts(student));
    }

    // The words of the registered name in lower case ("TEO CHEE" gives teo, chee).
    /**
     * Returns normalized name components used for header matching.
     * @param student the registered student identity.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static List<String> nameParts(Student student) {
        List<String> parts = new ArrayList<>();
        for (String part : student.fullName().toLowerCase().split("\\s+")) {
            if (!part.isEmpty()) {
                parts.add(part);
            }
        }
        return parts;
    }

    /**
     * Reports whether text contains every requested name component.
     * @param text the text to parse, render, or escape.
     * @param parts the argument supplied to this operation.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static boolean containsAll(String text, List<String> parts) {
        for (String part : parts) {
            if (!text.contains(part)) {
                return false;
            }
        }
        return true;
    }

    // The file content with a header block at the top (same format as the exam's), using the file's own line endings.
    /**
     * Returns source content with a corrected student header prepended.
     * @param content the argument supplied to this operation.
     * @param student the registered student identity.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static String withHeader(String content, Student student) {
        String newline = content.contains("\r\n") ? "\r\n" : "\n";
        String block = "/*" + newline
                + " * Name: " + displayName(student) + newline
                + " * Email ID: " + student.username() + newline
                + " */" + newline;
        int insertAt = content.startsWith(BOM) ? BOM.length() : 0;
        return content.substring(0, insertAt) + block + content.substring(insertAt);
    }

    // The scoresheet writes names in capitals (TEO CHEE); the exam header looks like "Teo Chee".
    /**
     * Returns the preferred human-readable name for a student.
     * @param student the registered student identity.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static String displayName(Student student) {
        if (student.fullName().isEmpty()) {
            return student.username();
        }
        StringBuilder name = new StringBuilder();
        for (String word : student.fullName().toLowerCase().split("\\s+")) {
            if (!word.isEmpty()) {
                if (name.length() > 0) {
                    name.append(' ');
                }
                name.append(Character.toUpperCase(word.charAt(0))).append(word.substring(1));
            }
        }
        return name.toString();
    }

    /**
     * Returns the final path component used as a display name.
     * @param path the file or directory path being inspected or written.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static String nameOf(Path path) {
        Path name = path.getFileName();
        return name == null ? path.toString() : name.toString();
    }
}
