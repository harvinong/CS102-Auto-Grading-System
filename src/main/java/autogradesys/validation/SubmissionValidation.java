package autogradesys.validation;

import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.function.Predicate;

import autogradesys.preflight.PreflightReport;
import autogradesys.validation.ValidationEvent.Type;

/**
 * Fixes common submission mistakes in place, right after the preflight has found them:
 * extra wrapper folders, mistyped username folders and missing name/email headers.
 * One failing submission never stops the others.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
public class SubmissionValidation {

    private final List<Student> students;
    private final UsernameResolver resolver;

    /**
     * @param students The registered students from the scoresheet.
     * @param confirm  Asks the instructor a yes/no question; true means yes.
     */
    public SubmissionValidation(List<Student> students, Predicate<String> confirm) {
        this.students = students;
        this.resolver = new UsernameResolver(students, confirm);
    }

    /**
     * @param submissions The submissions folder the preflight scanned.
     * @param preflight   The preflight report of that folder.
     * @return What was fixed, what still needs attention, and each identified student's folder.
     */
    public ValidationReport run(Path submissions, PreflightReport preflight) {
        List<ValidationEvent> events = new ArrayList<>();
        Map<String, Path> identified = new TreeMap<>();

        // Hierarchy first: it uses the preflight's paths, which a rename would make out of date.
        events.addAll(HierarchyFixer.flattenWrappers(submissions, preflight));

        for (String folder : preflight.students()) {
            Path dir = submissions.resolve(folder);
            // The template copy, archives and links have no student folder to fix.
            if (folder.equals(preflight.templateName()) || !Files.isDirectory(dir, LinkOption.NOFOLLOW_LINKS)) {
                continue;
            }
            resolver.resolve(folder, dir, events).ifPresent(identity -> {
                String username = identity.student().username();
                if (identified.containsKey(username)) {
                    events.add(new ValidationEvent(folder, Type.USERNAME_DUPLICATE, folder + "/",
                            "another folder is already matched to " + username));
                    return;
                }
                identified.put(username, identity.dir());
                events.addAll(HeaderFixer.fixAll(folder, identity.dir(), identity.student(), students));
            });
        }
        return new ValidationReport(events, identified);
    }
}
