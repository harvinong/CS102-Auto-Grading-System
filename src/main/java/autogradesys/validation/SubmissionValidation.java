package autogradesys.validation;

import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.function.Predicate;

import autogradesys.preflight.PreflightReport;
import autogradesys.validation.ValidationEvent.Type;

/**
 * Fixes common submission mistakes in the working copy, right after the preflight has found them:
 * missing question folders and files (restored from the original submission), extra wrapper folders,
 * mistyped username folders and missing name/email headers.
 * One failing submission never stops the others.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
public class SubmissionValidation {

    private final List<Student> students;
    private final UsernameResolver resolver;
    private final MissingRestorer restorer;
    private final SubmissionCache cache;

    /**
     * @param students The registered students from the scoresheet.
     * @param confirm  Asks the instructor a yes/no question; true means yes.
     * @param cache    The working copy, which knows each student's original submission.
     */
    public SubmissionValidation(List<Student> students, Predicate<String> confirm, SubmissionCache cache) {
        this.students = students;
        this.resolver = new UsernameResolver(students, confirm);
        this.restorer = new MissingRestorer(cache);
        this.cache = cache;
    }

    /**
     * @param submissions The working copy the preflight scanned.
     * @param preflight   The preflight report of that folder.
     * @return What was fixed, what still needs attention, and each identified student's folder.
     */
    public ValidationReport run(Path submissions, PreflightReport preflight) {
        List<ValidationEvent> events = new ArrayList<>();
        Map<String, Path> identified = new TreeMap<>();
        // Which folder already has each registered username, so a mistyped folder is never renamed onto another one unasked.
        Map<String, String> owners = UsernameResolver.owners(preflight.students(), students);
        // Folders that were replaced by a renamed one. The name may now belong to the new folder, so it is not looked at again.
        Set<String> replacedFolders = new HashSet<>();

        // Both steps use the preflight's paths, which a rename would make out of date, so they come first.
        // Restoring comes before the hierarchy fix because the preflight reported paths inside any wrapper folder.
        events.addAll(restorer.restore(submissions, preflight));
        events.addAll(HierarchyFixer.flattenWrappers(submissions, preflight));

        for (String folder : preflight.students()) {
            Path dir = submissions.resolve(folder);
            // The template copy, archives, links and replaced folders have no student folder to fix.
            if (folder.equals(preflight.templateName()) || replacedFolders.contains(folder)
                    || !Files.isDirectory(dir, LinkOption.NOFOLLOW_LINKS)) {
                continue;
            }
            resolver.resolve(folder, dir, events, owners).ifPresent(identity -> {
                String username = identity.student().username();
                if (identity.replaced() != null) {
                    // The folder that used this name was replaced: forget what was found or fixed in it.
                    replacedFolders.add(identity.replaced());
                    identified.remove(username);
                    events.removeIf(event -> event.student().equals(identity.replaced()));
                }
                String workingName = SubmissionFiles.nameOf(identity.dir());
                if (!workingName.equals(folder)) {
                    // Keep the link to the original submission after a rename.
                    cache.renamed(folder, workingName);
                }
                if (identified.containsKey(username)) {
                    events.add(new ValidationEvent(folder, Type.USERNAME_DUPLICATE, folder + "/",
                            "another folder is already matched to " + username));
                    return;
                }
                identified.put(username, identity.dir());
                events.addAll(HeaderFixer.fixAll(folder, identity.dir(), identity.student(), students));
            });
        }
        return new ValidationReport(events, identified);
    }
}
