package autogradesys.validation;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collection;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.function.Predicate;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import autogradesys.validation.ValidationEvent.Type;

/**
 * Works out which registered student a submission folder belongs to. A mistyped name is renamed
 * to the registered username once the instructor confirms it is a typo. If another folder already
 * uses that username, the instructor is asked whether to replace it, so a student never ends up
 * with two folders.
 */
// Generated by Claude (Anthropic); adapted from the team's original Validation.java
public class UsernameResolver {

    // Folder names may start with a term prefix such as "2023-2024-"; the username is the rest.
    private static final Pattern FOLDER_NAME = Pattern.compile("^(?:\\d{4}-\\d{4}-)?(.+)$");
    // Hidden name given to the folder being replaced while the rename happens, so a failed rename can be undone.
    private static final String ASIDE_PREFIX = ".replaced-";

    /**
     * The student a folder belongs to, and where that folder is now (it may have been renamed).
     *
     * @param replaced Name of the folder that was removed to make room for this one, or null.
     */
    public record Identity(Student student, Path dir, String replaced) {
    }

    private final List<Student> students;
    private final Predicate<String> confirm;

    /**
     * @param students The registered students from the scoresheet.
     * @param confirm  Asks the instructor a yes/no question; true means yes.
     */
    public UsernameResolver(List<Student> students, Predicate<String> confirm) {
        this.students = students;
        this.confirm = confirm;
    }

    /**
     * @param folder Name of the student's folder.
     * @param dir    The student's folder.
     * @param events Collects what happened.
     * @param owners Registered username (lower case) mapped to the folder that already has that exact name;
     *               updated when a folder is renamed.
     * @return The identity, or empty if the folder could not be matched to a registered student.
     */
    public Optional<Identity> resolve(String folder, Path dir, List<ValidationEvent> events,
            Map<String, String> owners) {
        String claimed = claimedUsername(folder);

        Optional<Student> exact = UsernameMatcher.findExact(claimed, students);
        if (exact.isPresent()) {
            return Optional.of(new Identity(exact.get(), dir, null));
        }

        Optional<Student> closest = UsernameMatcher.findClosest(claimed, students);
        if (closest.isEmpty()) {
            events.add(new ValidationEvent(folder, Type.USERNAME_UNREGISTERED, folder + "/",
                    "no registered student is close to '" + claimed + "'"));
            return Optional.empty();
        }

        Student match = closest.get();
        // A different folder that already has the correct name, or null.
        String owner = owners.get(match.username().toLowerCase(Locale.ROOT));
        String question = "'" + match.username() + "' is the closest registered name to '" + claimed + "'";

        if (owner == null) {
            if (!confirm.test(question + ". Is this a typo?")) {
                events.add(new ValidationEvent(folder, Type.TYPO_DECLINED, folder + "/",
                        "'" + claimed + "' was not changed and is not matched to a student"));
                return Optional.empty();
            }
        } else if (!confirm.test(question + ", but '" + owner + "' already uses it. Replace '" + owner
                + "' with '" + folder + "' (renamed to " + match.username() + ")?")) {
            events.add(new ValidationEvent(folder, Type.TYPO_DECLINED, folder + "/",
                    "kept both folders: '" + folder + "' is not matched to a student because '" + owner
                            + "' already uses " + match.username() + "; remove one of them by hand"));
            return Optional.empty();
        }
        return rename(folder, dir, match, owner, owners, events);
    }

    // Renames the folder to the registered username, first moving aside the folder that already used the name.
    /**
     * Renames a working submission folder and records the replacement for later matching.
     */
    private Optional<Identity> rename(String folder, Path dir, Student match, String owner,
            Map<String, String> owners, List<ValidationEvent> events) {
        Path renamed = dir.resolveSibling(match.username());
        Path ownerDir = owner == null ? null : dir.resolveSibling(owner);
        Path aside = owner == null ? null : dir.resolveSibling(ASIDE_PREFIX + owner);
        try {
            if (owner != null) {
                // Move the old folder aside instead of deleting it, so it can be put back if the rename fails.
                Files.move(ownerDir, aside);
            }
            try {
                // Files.move fails instead of overwriting when the target exists.
                Files.move(dir, renamed);
            } catch (IOException e) {
                if (owner != null) {
                    Files.move(aside, ownerDir);
                }
                throw e;
            }
        } catch (IOException e) {
            events.add(new ValidationEvent(folder, Type.FIX_FAILED, folder + "/",
                    "could not rename it to " + match.username() + " (" + e.getMessage() + ")"));
            return Optional.empty();
        }
        if (owner != null) {
            SubmissionFiles.deleteTree(aside);
        }
        owners.put(match.username().toLowerCase(Locale.ROOT), match.username());
        events.add(new ValidationEvent(folder, Type.FOLDER_RENAMED, folder + "/", owner == null
                ? "renamed to " + match.username()
                : "renamed to " + match.username() + ", replacing '" + owner + "' which used that name"));
        return Optional.of(new Identity(match, renamed, owner));
    }

    /** The username a folder name claims to be, with any term prefix removed. */
    public static String claimedUsername(String folder) {
        Matcher matcher = FOLDER_NAME.matcher(folder);
        return matcher.matches() ? matcher.group(1) : folder;
    }

    /**
     * Which folder already has each registered username as its (exact) name.
     *
     * @return Registered username in lower case mapped to the folder name; the first folder wins.
     */
    public static Map<String, String> owners(Collection<String> folders, List<Student> students) {
        Map<String, String> owners = new HashMap<>();
        for (String folder : folders) {
            UsernameMatcher.findExact(claimedUsername(folder), students)
                    .ifPresent(student -> owners.putIfAbsent(student.username().toLowerCase(Locale.ROOT), folder));
        }
        return owners;
    }
}
