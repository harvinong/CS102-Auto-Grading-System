package autogradesys.validation;

import java.io.IOException;
import java.io.Reader;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Properties;
import java.util.Set;
import java.util.TreeMap;
import java.util.stream.Stream;
import java.util.regex.Pattern;
import autogradesys.submission.Submission;
import autogradesys.submission.SubmissionIterator;
import autogradesys.submission.SubmissionUnzipper;

import autogradesys.validation.ValidationEvent.Type;

/**
 * Builds the working copy of a submissions folder inside the cache folder: zips are extracted and
 * plain folders are copied. All fixing and grading happens on the copy, so the originals stay
 * untouched, and the grader can edit the copy by hand.
 *
 * The copy is kept between runs and an existing student folder is never overwritten, so manual
 * edits survive. Delete the folder inside the cache to start fresh.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
public class SubmissionCache {

    /** The cache folder, relative to where the program is run (the project root). */
    public static final Path DEFAULT_ROOT = Path.of("cache");

    private static final String MANIFEST_SUFFIX = ".manifest";
    private static final String SOURCE_KEY = "source";
    private static final String RENAMED_PREFIX = "renamed.";
    private static final String DEFAULT_NAME = "submissions";

    private final Path cacheRoot;
    // Original student name -> the folder or zip it came from (rebuilt on every prepare).
    private final Map<String, Path> sources = new TreeMap<>();
    // Working folder name -> original student name, for folders renamed by the validation (kept in the manifest).
    private final Map<String, String> renamed = new TreeMap<>();
    private Path workingDir;
    private Path manifestFile;
    private String sourceRecord;

    /**
     * Creates a submission cache instance.
     */
    public SubmissionCache(Path cacheRoot) {
        this.cacheRoot = cacheRoot;
    }

    /** The working copy folder (valid after {@link #prepare}). */
    public Path workingDir() {
        return workingDir;
    }

    /**
     * Makes sure every submission is in the working copy, adding the ones that are not there yet.
     *
     * @param submissions The folder of original student submissions.
     * @return Where the working copy is and what happened while preparing it.
     */
    public CacheReport prepare(Path submissions) {
        List<ValidationEvent> events = new ArrayList<>();
        Path original = submissions.toAbsolutePath().normalize();
        String name = SubmissionFiles.nameOf(original).isEmpty() ? DEFAULT_NAME : SubmissionFiles.nameOf(original);
        workingDir = cacheRoot.resolve(name).toAbsolutePath().normalize();
        manifestFile = cacheRoot.resolve(name + MANIFEST_SUFFIX);
        sourceRecord = original.toString();
        sources.clear();
        renamed.clear();

        try {
            loadManifest();
            Files.createDirectories(workingDir);
            saveManifest();
            findSources(original, events);
        } catch (IOException e) {
            events.add(new ValidationEvent("", Type.COPY_FAILED, name,
                    "the working copy could not be prepared (" + e.getMessage() + ")"));
            return new CacheReport(workingDir, events, 0, 0, false);
        }

        int created = 0;
        int reused = 0;
        for (Map.Entry<String, Path> source : sources.entrySet()) {
            if (hasWorkingFolder(source.getKey())) {
                reused++;
                continue;
            }
            ValidationEvent event = build(original, source.getKey(), source.getValue());
            if (event != null) {
                events.add(event);
            }
            if (event == null || event.fixed()) {
                created++;
            }
        }
        return new CacheReport(workingDir, events, created, reused, true);
    }

    /** The original folder or zip that a working folder came from, if it is known. */
    public Optional<Path> sourceOf(String workingFolder) {
        return Optional.ofNullable(sources.get(renamed.getOrDefault(workingFolder, workingFolder)));
    }

    /** Remembers that the validation renamed a working folder, so it is still matched to its original. */
    public void renamed(String from, String to) {
        String originalName = renamed.getOrDefault(from, from);
        renamed.remove(from);
        if (!originalName.equals(to)) {
            renamed.put(to, originalName);
        }
        try {
            saveManifest();
        } catch (IOException e) {
            // Best effort: without the note, the next run would extract the original again beside the fixed folder.
        }
    }

    // Puts one submission into the working copy; returns an event, or null for a plain folder that copied fine.
    /**
     * Build.
     */
    private ValidationEvent build(Path originals, String student, Path source) {
        Path destination = workingDir.resolve(student);
        String shown = originals.relativize(source).toString().replace('\\', '/');
        boolean zip = SubmissionFiles.isZipFile(source);
        try {
            if (zip) {
                int files = SubmissionUnzipper.unzip(source, destination);
                return new ValidationEvent(student, Type.ARCHIVE_EXTRACTED, shown,
                        "extracted " + files + (files == 1 ? " file" : " files"));
            }
            SubmissionFiles.copyMissing(source, destination);
            return null;
        } catch (IOException e) {
            SubmissionFiles.deleteTree(destination);
            return new ValidationEvent(student, zip ? Type.ARCHIVE_FAILED : Type.COPY_FAILED, shown,
                    "could not " + (zip ? "extract" : "copy") + " it (" + e.getMessage() + "); nothing was left behind");
        }
    }

    // Finds what each student's original is: a folder, or a zip (beside or inside the folder).
    /**
     * Find sources.
     */
    private void findSources(Path originals, List<ValidationEvent> events) throws IOException {
        // Use the teammate iterator for the canonical named-archive discovery path.
        SubmissionIterator namedArchives = new SubmissionIterator(originals,
                Pattern.compile("^\\d{4}-\\d{4}-(.+)\\.zip$", Pattern.CASE_INSENSITIVE));
        // Zips already claimed under their username, so the loop below does not add them again under the full file name.
        Set<Path> namedZips = new HashSet<>();
        for (Submission archive : namedArchives) {
            sources.putIfAbsent(archive.getUsername(), archive.getZipPath());
            namedZips.add(archive.getZipPath());
        }
        List<Path> children;
        try (Stream<Path> stream = Files.list(originals)) {
            children = stream.sorted().toList();
        }
        // A zip beside a real folder of the same name is not a separate student (same rule as the preflight).
        Set<String> folderNames = new HashSet<>();
        for (Path child : children) {
            if (Files.isDirectory(child, LinkOption.NOFOLLOW_LINKS) && !SubmissionFiles.isJunk(child.getFileName())) {
                folderNames.add(SubmissionFiles.nameOf(child).toLowerCase(Locale.ROOT));
            }
        }
        for (Path child : children) {
            // The entry's own file or folder name (a zip still has its .zip ending here), used when it is stored as a source.
            String name = SubmissionFiles.nameOf(child);
            // Junk is a name starting with a dot (.DS_Store) or the __MACOSX folder; it is never a student.
            if (SubmissionFiles.isJunk(child.getFileName())) {
                // Record an IGNORED_JUNK event with the path relative to the submissions folder; AutoGradeMenu.runGrader turns it into a quiet "note" record.
                events.add(new ValidationEvent("", ValidationEvent.Type.IGNORED_JUNK,
                        originals.relativize(child).toString().replace('\\', '/'), "ignored"));
                // Skip the checks below so the junk entry is not copied into the working copy.
                continue;
            }
            if (Files.isSymbolicLink(child)) {
                events.add(new ValidationEvent(name, Type.COPY_FAILED, name, "a symbolic link, so it was not copied"));
            } else if (Files.isDirectory(child, LinkOption.NOFOLLOW_LINKS)) {
                Path onlyZip = SubmissionFiles.onlyContentIsZip(child);
                sources.putIfAbsent(name, onlyZip != null ? onlyZip : child);
            } else if (SubmissionFiles.isZipFile(child) && !namedZips.contains(child)
                    && !folderNames.contains(SubmissionFiles.stem(name).toLowerCase(Locale.ROOT))) {
                sources.putIfAbsent(SubmissionFiles.stem(name), child);
            }
        }
    }

    // True if the student is already in the working copy (under its own name or a name the validation gave it).
    /**
     * Returns has working folder.
     */
    private boolean hasWorkingFolder(String student) {
        if (Files.exists(workingDir.resolve(student), LinkOption.NOFOLLOW_LINKS)) {
            return true;
        }
        return renamed.entrySet().stream().anyMatch(entry -> entry.getValue().equals(student)
                && Files.isDirectory(workingDir.resolve(entry.getKey())));
    }

    // Reads the manifest. A working copy of a different submissions folder, or a folder this program did not
    // create, is refused so that old files are never graded by mistake.
    /**
     * Load manifest.
     */
    private void loadManifest() throws IOException {
        if (!Files.exists(manifestFile)) {
            if (hasContent(workingDir)) {
                throw new IOException(workingDir + " already exists and was not created by this program; "
                        + "move or delete it");
            }
            return;
        }
        Properties properties = new Properties();
        try (Reader reader = Files.newBufferedReader(manifestFile, StandardCharsets.UTF_8)) {
            properties.load(reader);
        }
        String recorded = properties.getProperty(SOURCE_KEY, "");
        if (!recorded.equalsIgnoreCase(sourceRecord)) {
            throw new IOException(workingDir + " holds a copy of a different submissions folder (" + recorded
                    + "); delete it or rename your submissions folder");
        }
        for (String key : properties.stringPropertyNames()) {
            if (key.startsWith(RENAMED_PREFIX)) {
                String working = key.substring(RENAMED_PREFIX.length());
                if (Files.isDirectory(workingDir.resolve(working))) {
                    renamed.put(working, properties.getProperty(key));
                }
            }
        }
    }

    /**
     * Save manifest.
     */
    private void saveManifest() throws IOException {
        Properties properties = new Properties();
        properties.setProperty(SOURCE_KEY, sourceRecord);
        renamed.forEach((working, originalName) -> properties.setProperty(RENAMED_PREFIX + working, originalName));
        Files.createDirectories(cacheRoot);
        try (Writer writer = Files.newBufferedWriter(manifestFile, StandardCharsets.UTF_8)) {
            properties.store(writer, "Working copy of a submissions folder. Do not edit.");
        }
    }

    /**
     * Returns has content.
     */
    private static boolean hasContent(Path dir) throws IOException {
        if (!Files.isDirectory(dir)) {
            return false;
        }
        try (Stream<Path> stream = Files.list(dir)) {
            return stream.findAny().isPresent();
        }
    }
}
