package autogradesys.validation;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

import autogradesys.validation.ValidationEvent.Type;

/**
 * Extracts student zip files into folders so the preflight and validation can look inside them.
 * It only creates new folders and files: it never overwrites or deletes anything that was there,
 * and a zip that fails to extract leaves nothing behind.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
public final class ArchiveExtractor {

    private static final String ZIP_EXTENSION = ".zip";
    // Limits that stop a "zip bomb" (a tiny zip that unpacks to gigabytes) from filling the disk.
    private static final long MAX_UNPACKED_BYTES = 200L * 1024 * 1024;
    private static final int MAX_ENTRIES = 5_000;
    private static final int BUFFER_SIZE = 8192;

    private ArchiveExtractor() {
    }

    /**
     * Extracts every zip in the submissions folder that has not been extracted yet:
     * <ul>
     * <li>frank.zip with no frank/ beside it is extracted into a new folder frank/;</li>
     * <li>a student folder whose only content is one zip is extracted into that folder.</li>
     * </ul>
     * A zip that sits beside its extracted folder is left alone.
     *
     * @param submissions The folder of student submissions.
     * @return One event per archive that was extracted or failed; nothing for archives left alone.
     */
    public static List<ValidationEvent> extractAll(Path submissions) {
        List<ValidationEvent> events = new ArrayList<>();
        List<Path> children;
        try (Stream<Path> stream = Files.list(submissions)) {
            children = stream.sorted().toList();
        } catch (IOException e) {
            events.add(new ValidationEvent("", Type.ARCHIVE_FAILED, submissions.toString(),
                    "could not list the submissions folder (" + e.getMessage() + ")"));
            return events;
        }

        // Lower-case names of the real folders, so a zip beside its folder is recognised (as in the preflight).
        Set<String> folderNames = new HashSet<>();
        for (Path child : children) {
            if (Files.isDirectory(child, LinkOption.NOFOLLOW_LINKS)) {
                folderNames.add(nameOf(child).toLowerCase(Locale.ROOT));
            }
        }

        for (Path child : children) {
            if (isZipFile(child)) {
                String stem = stem(nameOf(child));
                // add() is false when a folder with that name already exists: nothing to do.
                if (folderNames.add(stem.toLowerCase(Locale.ROOT))) {
                    events.add(extract(submissions, child, submissions.resolve(stem), stem, true));
                }
            } else if (Files.isDirectory(child, LinkOption.NOFOLLOW_LINKS)
                    && !SubmissionFiles.isJunk(child.getFileName())) {
                Path onlyZip = onlyContentIsZip(child);
                if (onlyZip != null) {
                    events.add(extract(submissions, onlyZip, child, nameOf(child), false));
                }
            }
        }
        return events;
    }

    // Extracts one zip into the destination folder; on any failure everything it created is removed.
    private static ValidationEvent extract(Path submissions, Path zipPath, Path destination, String student,
            boolean createDestination) {
        String shownZip = submissions.relativize(zipPath).toString().replace('\\', '/');
        Path dest = destination.toAbsolutePath().normalize();
        List<Path> created = new ArrayList<>();
        try (ZipFile zip = open(zipPath)) {
            if (zip.size() > MAX_ENTRIES) {
                throw new IOException("it has more than " + MAX_ENTRIES + " entries");
            }
            if (createDestination) {
                Files.createDirectory(dest);
                created.add(dest);
            }
            int files = unpack(zip, dest, created);
            return new ValidationEvent(student, Type.ARCHIVE_EXTRACTED, shownZip,
                    "extracted " + files + " files into " + nameOf(destination) + "/");
        } catch (IOException | RuntimeException e) {
            undo(created);
            return new ValidationEvent(student, Type.ARCHIVE_FAILED, shownZip,
                    "could not extract it (" + e.getMessage() + "); nothing was left behind");
        }
    }

    // Writes every entry under dest and returns how many files were written.
    private static int unpack(ZipFile zip, Path dest, List<Path> created) throws IOException {
        long totalBytes = 0;
        int files = 0;
        Enumeration<? extends ZipEntry> entries = zip.entries();
        while (entries.hasMoreElements()) {
            ZipEntry entry = entries.nextElement();
            Path target = dest.resolve(entry.getName()).normalize();

            // Zip Slip: an entry like "../../x" must never be written outside the destination folder.
            if (!target.startsWith(dest)) {
                throw new IOException("unsafe entry '" + entry.getName() + "' would be written outside the folder");
            }
            if (target.equals(dest) || SubmissionFiles.isJunk(dest.relativize(target))) {
                continue;
            }
            if (entry.isDirectory()) {
                makeDirectories(target, dest, created);
                continue;
            }

            makeDirectories(target.getParent(), dest, created);
            // CREATE_NEW refuses to overwrite a file that is already there.
            try (InputStream in = zip.getInputStream(entry);
                    OutputStream out = Files.newOutputStream(target, StandardOpenOption.CREATE_NEW)) {
                created.add(target);
                byte[] buffer = new byte[BUFFER_SIZE];
                int read;
                while ((read = in.read(buffer)) != -1) {
                    totalBytes += read;
                    if (totalBytes > MAX_UNPACKED_BYTES) {
                        throw new IOException("it unpacks to more than " + MAX_UNPACKED_BYTES / (1024 * 1024) + " MB");
                    }
                    out.write(buffer, 0, read);
                }
            }
            files++;
        }
        return files;
    }

    // Creates each missing folder from base down to dir, remembering them so a failure can undo it.
    private static void makeDirectories(Path dir, Path base, List<Path> created) throws IOException {
        Path current = base;
        for (Path part : base.relativize(dir)) {
            current = current.resolve(part);
            if (!Files.isDirectory(current)) {
                Files.createDirectory(current);
                created.add(current);
            }
        }
    }

    // Removes what a failed extraction created, newest first so files go before their folders.
    private static void undo(List<Path> created) {
        for (int i = created.size() - 1; i >= 0; i--) {
            try {
                Files.deleteIfExists(created.get(i));
            } catch (IOException e) {
                // Best effort: the failure event already tells the instructor something went wrong.
            }
        }
    }

    // Opens the zip; older Windows zips can hold entry names that are not valid UTF-8.
    private static ZipFile open(Path zipPath) throws IOException {
        try {
            return new ZipFile(zipPath.toFile());
        } catch (IllegalArgumentException e) {
            return new ZipFile(zipPath.toFile(), StandardCharsets.ISO_8859_1);
        }
    }

    // The one zip a folder contains, if that zip is the folder's only content; otherwise null.
    private static Path onlyContentIsZip(Path folder) {
        try (Stream<Path> stream = Files.list(folder)) {
            List<Path> items = stream.filter(p -> !SubmissionFiles.isJunk(p.getFileName())).toList();
            return items.size() == 1 && isZipFile(items.get(0)) ? items.get(0) : null;
        } catch (IOException e) {
            return null;
        }
    }

    // True for a real file (not a link) whose name ends in .zip in any letter case.
    private static boolean isZipFile(Path path) {
        return Files.isRegularFile(path, LinkOption.NOFOLLOW_LINKS)
                && nameOf(path).toLowerCase(Locale.ROOT).endsWith(ZIP_EXTENSION);
    }

    // "frank.zip" -> "frank".
    private static String stem(String zipName) {
        return zipName.substring(0, zipName.length() - ZIP_EXTENSION.length());
    }

    private static String nameOf(Path path) {
        Path name = path.getFileName();
        return name == null ? path.toString() : name.toString();
    }
}
