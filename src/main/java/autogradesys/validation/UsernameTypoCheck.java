package autogradesys.validation;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;

import autogradesys.preflight.PreflightFinding;
import autogradesys.preflight.PreflightFinding.Category;
import autogradesys.preflight.PreflightFinding.Severity;
import autogradesys.preflight.PreflightReport;

/**
 * Adds a USERNAME_TYPO finding to a preflight report for every folder whose name is not a registered
 * username but is close to one, so the instructor is alerted in the check, before any fix is run.
 * It only reports; the rename itself is done (after confirmation) by {@link UsernameResolver}.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
public final class UsernameTypoCheck {

    /**
     * Initializes the check that suggests registered students for misspelled folder names.
     */
    private UsernameTypoCheck() {
    }

    /**
     *         or the same report if no folder name looks like a typo.
     * @param report the argument supplied to this operation.
     * @param students the registered student identities used for matching.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    public static PreflightReport addFindings(PreflightReport report, List<Student> students) {
        Map<String, String> owners = UsernameResolver.owners(report.students(), students);
        List<PreflightFinding> all = new ArrayList<>();

        for (String folder : report.students()) {
            // A copy of the blank template is not a student's work.
            if (report.templateCopy(folder)) {
                continue;
            }
            String claimed = UsernameResolver.claimedUsername(folder);
            if (UsernameMatcher.findExact(claimed, students).isPresent()) {
                continue;
            }
            Optional<Student> closest = UsernameMatcher.findClosest(claimed, students);
            if (closest.isPresent()) {
                String owner = owners.get(closest.get().username().toLowerCase(Locale.ROOT));
                all.add(finding(folder, claimed, closest.get(), owner));
            }
        }
        if (all.isEmpty()) {
            return report;
        }
        all.addAll(report.findings());
        return new PreflightReport(report.templateName(), report.students(), all);
    }

    // One USERNAME_TYPO finding; owner is the folder that already uses the correct name, or null.
    /**
     * Creates a preflight finding describing a likely username typo and its owner.
     * @param folder the directory whose contents are processed.
     * @param claimed the argument supplied to this operation.
     * @param match the argument supplied to this operation.
     * @param owner the argument supplied to this operation.
     * @return the result of this operation; an empty, absent, or false result indicates that no matching value or successful update was available.
     */
    private static PreflightFinding finding(String folder, String claimed, Student match, String owner) {
        String message = "'" + match.username() + "' is the closest registered name to '" + claimed
                + "'. This is likely a typo."
                + (owner == null ? "" : " ('" + owner + "' already uses that name.)");
        String fix = owner == null
                ? "Choose \"Fix common mistakes automatically\" to rename it after you confirm"
                : "Choose \"Fix common mistakes automatically\" to pick which folder to keep";
        return new PreflightFinding(folder, Category.USERNAME_TYPO, Severity.ERROR, folder + "/", message, fix);
    }
}
