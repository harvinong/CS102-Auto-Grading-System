package autogradesys.validation;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;

import autogradesys.preflight.PreflightFinding;
import autogradesys.preflight.PreflightFinding.Category;
import autogradesys.preflight.PreflightReport;
import autogradesys.validation.ValidationEvent.Type;

/**
 * Puts back question folders and files that are missing from the working copy
 * (for example because
 * the grader deleted them by accident) by reading them again from the student's
 * original submission.
 * If the original does not have them either, the student never submitted them,
 * and that is reported.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
public class MissingRestorer {

    private final SubmissionCache cache;

    public MissingRestorer(SubmissionCache cache) {
        this.cache = cache;
    }

    /**
     * @param workingDir The working copy that the preflight scanned.
     * @param preflight  The preflight report of that folder; its MISSING_QUESTION
     *                   and MISSING_FILE findings are used.
     * @return One event per missing question folder or file: restored, or still
     *         missing.
     */
    public List<ValidationEvent> restore(Path workingDir, PreflightReport preflight) {
        List<ValidationEvent> events = new ArrayList<>();
        for (PreflightFinding finding : preflight.findings()) {
            boolean question = finding.category() == Category.MISSING_QUESTION;
            boolean file = finding.category() == Category.MISSING_FILE;
            // A copy of the blank template is not a student's work, so leave it alone.
            if ((question || file) && !finding.student().equals(preflight.templateName())) {
                events.add(restoreOne(workingDir, finding, question ? 1 : 2));
            }
        }
        return events;
    }

    // Restores one item. Its name is the last `parts` parts of the finding's path:
    // "Q2" or "Q1/Q1b.java".
    private ValidationEvent restoreOne(Path workingDir, PreflightFinding finding, int parts) {
        Path target = workingDir.resolve(finding.path()).normalize();
        int count = target.getNameCount();
        String item = target.subpath(count - parts, count).toString().replace('\\', '/');
        Path projectDir = target;
        for (int i = 0; i < parts; i++) {
            projectDir = projectDir.getParent();
        }

        Optional<Path> source = cache.sourceOf(finding.student());
        if (source.isEmpty()) {
            return missing(finding,
                    item + " is missing and its original submission could not be found to restore it from");
        }
        try {
            int restored = SubmissionFiles.isZipFile(source.get())
                    ? ArchiveExtractor.restore(source.get(), projectDir, item)
                    : restoreFromFolder(source.get(), projectDir, item);
            if (restored > 0) {
                return new ValidationEvent(finding.student(), Type.ITEM_RESTORED, finding.path(),
                        "was missing, restored " + item + " from the original submission (" + restored
                                + (restored == 1 ? " file)" : " files)"));
            }
            return missing(finding, item + " is not in the original submission either: the student did not submit it");
        } catch (IOException e) {
            return missing(finding, item + " is missing and could not be restored (" + e.getMessage() + ")");
        }
    }

    private static ValidationEvent missing(PreflightFinding finding, String message) {
        return new ValidationEvent(finding.student(), Type.ITEM_MISSING, finding.path(), message);
    }

    // Copies the missing item from the original submission,
    // even if the original submission contains multiple wrappers.
    private static int restoreFromFolder(Path originalFolder, Path projectDir, String item) throws IOException {

        // First check whether the item exists directly in the original folder.
        Path source = originalFolder.resolve(item);

        if (Files.exists(source, LinkOption.NOFOLLOW_LINKS)) {
            return SubmissionFiles.copyMissing(
                    source, projectDir.resolve(item));
        }

        // Otherwise, search recursively through the original submission.
        source = findOriginalItem(originalFolder, item);

        // Nothing matching the requested item was found.
        if (source == null) {
            return 0;
        }

        return SubmissionFiles.copyMissing(
                source, projectDir.resolve(item));
    }

    /**
     * Searches recursively for the requested item inside the original submission.
     */
    private static Path findOriginalItem(Path folder, String item)
            throws IOException {

        // Check whether the requested item exists at this level.
        Path candidate = folder.resolve(item);

        if (Files.exists(candidate, LinkOption.NOFOLLOW_LINKS)) {
            return candidate;
        }

        // Search through genuine subdirectories.
        try (Stream<Path> children = Files.list(folder)) {

            for (Path child : children.sorted().toList()) {

                // Never follow symbolic links or search junk folders.
                if (SubmissionFiles.isJunk(child.getFileName())
                        || !Files.isDirectory(child, LinkOption.NOFOLLOW_LINKS)) {
                    continue;
                }

                Path found = findOriginalItem(child, item);

                if (found != null) {
                    return found;
                }
            }
        }

        return null;
    }
}
