package autogradesys.validation;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;

import autogradesys.preflight.PreflightFinding;
import autogradesys.preflight.PreflightFinding.Category;
import autogradesys.preflight.PreflightReport;
import autogradesys.validation.ValidationEvent.Type;

/**
 * Puts back question folders and files that are missing from the working copy.
 *
 * Missing question folders and Java files are restored from the student's
 * original submission.
 *
 * Missing resource files are restored from the configured Starting Folder
 * template, since these files are provided by the instructor rather than
 * submitted by the student.
 *
 * The original submissions and the template are never modified.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
public class MissingRestorer {

    private final SubmissionCache cache;
    private final Path templateDir;

    /**
     * @param cache      The working copy, which knows each student's original submission.
     * @param templateDir The configured Starting Folder template.
     */
    public MissingRestorer(SubmissionCache cache, Path templateDir) {
        this.cache = cache;
        this.templateDir = templateDir == null ? null : templateDir.toAbsolutePath().normalize();
    }

    /**
     * Backwards-compatible constructor for existing code that does not provide
     * a template path. Missing questions and Java files can still be restored,
     * but missing resources cannot.
     */
    public MissingRestorer(SubmissionCache cache) {
        this(cache, null);
    }

    /**
     * @param workingDir The working copy that the preflight scanned.
     * @param preflight  The preflight report of that folder.
     * @return Events describing restored items or items that are still missing.
     */
    public List<ValidationEvent> restore(Path workingDir, PreflightReport preflight) {
        List<ValidationEvent> events = new ArrayList<>();

        for (PreflightFinding finding : preflight.findings()) {
            boolean question = finding.category() == Category.MISSING_QUESTION;
            boolean file = finding.category() == Category.MISSING_FILE;
            boolean resource = finding.category() == Category.MISSING_RESOURCE;

            // A copy of the blank template is not a student's work, so leave it alone.
            if (finding.student().equals(preflight.templateName())) {
                continue;
            }

            if (question || file) {
                // Preserve the existing behaviour: restore from the student's
                // original submission.
                events.add(restoreOne(workingDir, finding, question ? 1 : 2));
            } else if (resource) {
                // Resources are supplied by the instructor, so restore them
                // from the Starting Folder template instead.
                events.add(restoreResource(workingDir, finding));
            }
        }

        return events;
    }

    // Restores one missing question folder or Java file from the student's
    // original submission.
    //
    // Its name is the last `parts` parts of the finding's path:
    // "Q2" or "Q1/Q1b.java".
    private ValidationEvent restoreOne(Path workingDir, PreflightFinding finding, int parts) {
        Path target = workingDir.resolve(finding.path()).normalize();
        int count = target.getNameCount();

        String item = target.subpath(count - parts, count).toString().replace('\\', '/');

        Path projectDir = target;
        for (int i = 0; i < parts; i++) {
            projectDir = projectDir.getParent();
        }

        Optional<Path> source = cache.sourceOf(finding.student());

        if (source.isEmpty()) {
            return missing(finding,
                    item + " is missing and its original submission could not be found to restore it from");
        }

        try {
            int restored = SubmissionFiles.isZipFile(source.get())
                    ? ArchiveExtractor.restore(source.get(), projectDir, item)
                    : restoreFromFolder(source.get(), projectDir, item);

            if (restored > 0) {
                return new ValidationEvent(finding.student(), Type.ITEM_RESTORED, finding.path(),
                        "was missing, restored " + item + " from the original submission (" + restored
                                + (restored == 1 ? " file)" : " files)"));
            }

            return missing(finding,
                    item + " is not in the original submission either: the student did not submit it");

        } catch (IOException e) {
            return missing(finding,
                    item + " is missing and could not be restored (" + e.getMessage() + ")");
        }
    }

    /**
     * Restores a missing resource file from the configured Starting Folder.
     *
     * Resource findings are generated for files directly inside a question
     * folder. Therefore, the last two path components identify the relative
     * location of the resource inside the template:
     *
     * Student123/Question1/students.txt
     *                    |
     *                    +-- Question1/students.txt
     *
     * The source is StartingFolder/Question1/students.txt.
     */
    private ValidationEvent restoreResource(Path workingDir, PreflightFinding finding) {
        if (templateDir == null) {
            return missing(finding,
                    "the resource is missing and could not be restored because the Starting Folder path was not provided");
        }

        try {
            Path workingRoot = workingDir.toAbsolutePath().normalize();
            Path target = workingRoot.resolve(finding.path()).normalize();

            // Ensure the finding does not point outside the working copy.
            if (!target.startsWith(workingRoot)) {
                return missing(finding,
                        "the resource is missing and its working-copy path is invalid");
            }

            // The resource is directly inside its question folder, so use
            // the final two components to locate it in the template.
            if (target.getNameCount() < 2) {
                return missing(finding,
                        "the resource is missing and its template path could not be determined");
            }

            Path relativeResource = target.subpath(
                    target.getNameCount() - 2,
                    target.getNameCount());

            Path source = templateDir.resolve(relativeResource).normalize();

            // Ensure the source remains inside the configured template.
            if (!source.startsWith(templateDir)) {
                return missing(finding,
                        "the resource is missing and its template path is invalid");
            }

            // Do not follow symbolic links. Only restore a genuine regular file.
            if (!Files.isRegularFile(source, LinkOption.NOFOLLOW_LINKS)) {
                return missing(finding,
                        relativeResource.toString().replace('\\', '/')
                                + " could not be found as a regular file in the Starting Folder template");
            }

            // Copy into the working copy without overwriting an existing item.
            int restored = SubmissionFiles.copyMissing(source, target);

            if (restored > 0) {
                return new ValidationEvent(
                        finding.student(),
                        Type.ITEM_RESTORED,
                        finding.path(),
                        "was missing, restored "
                                + relativeResource.toString().replace('\\', '/')
                                + " from the Starting Folder template ("
                                + restored + (restored == 1 ? " file)" : " files)"));
            }

            return missing(finding,
                    relativeResource.toString().replace('\\', '/')
                            + " could not be restored from the Starting Folder template");

        } catch (IOException e) {
            return missing(finding,
                    "the resource is missing and could not be restored from the Starting Folder template ("
                            + e.getMessage() + ")");
        }
    }

    private static ValidationEvent missing(PreflightFinding finding, String message) {
        return new ValidationEvent(finding.student(), Type.ITEM_MISSING, finding.path(), message);
    }

    // Copies the missing item from the original submission,
    // even if the original submission contains multiple wrappers.
    private static int restoreFromFolder(Path originalFolder, Path projectDir, String item)
            throws IOException {

        // First check whether the item exists directly in the original folder.
        Path source = originalFolder.resolve(item);

        if (Files.exists(source, LinkOption.NOFOLLOW_LINKS)) {
            return SubmissionFiles.copyMissing(
                    source, projectDir.resolve(item));
        }

        // Otherwise, search recursively through the original submission.
        source = findOriginalItem(originalFolder, item);

        // Nothing matching the requested item was found.
        if (source == null) {
            return 0;
        }

        return SubmissionFiles.copyMissing(
                source, projectDir.resolve(item));
    }

    /**
     * Searches recursively for the requested item inside the original submission.
     */
    private static Path findOriginalItem(Path folder, String item) throws IOException {

        // Check whether the requested item exists at this level.
        Path candidate = folder.resolve(item);

        if (Files.exists(candidate, LinkOption.NOFOLLOW_LINKS)) {
            return candidate;
        }

        // Search through genuine subdirectories.
        try (Stream<Path> children = Files.list(folder)) {
            for (Path child : children.sorted().toList()) {

                // Never follow symbolic links or search junk folders.
                if (SubmissionFiles.isJunk(child.getFileName())
                        || !Files.isDirectory(child, LinkOption.NOFOLLOW_LINKS)) {
                    continue;
                }

                Path found = findOriginalItem(child, item);

                if (found != null) {
                    return found;
                }
            }
        }

        return null;
    }
}
