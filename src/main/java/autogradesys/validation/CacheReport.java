package autogradesys.validation;

import java.io.PrintStream;
import java.nio.file.Path;
import java.util.List;

/**
 * What {@link SubmissionCache} did to prepare the working copy.
 *
 * @param workingDir The folder holding the working copy. Preflight, validation and grading use this folder.
 * @param events     One event per archive extracted or per problem; plain folders that copied fine have none.
 * @param created    How many submissions were newly extracted or copied.
 * @param reused     How many were already in the cache from an earlier run, and were left as they are.
 * @param usable     False if the working copy could not be set up at all, so grading must not go on.
 */
// Generated by Claude (Anthropic); reviewed and adapted by the team
/**
 * Stores cache preparation events and counts for created and reused working copies.
 */
public record CacheReport(Path workingDir, List<ValidationEvent> events, int created, int reused, boolean usable) {

    // How many archives or folders could not be put into the working copy.
    /**
     * Counts cache preparation events that represent failures.
     */
    public long failedCount() {
        return events.stream().filter(event -> !event.fixed()).count();
    }

    // Writes the report to the given stream (the console in the real program).
    /**
     * Writes the current report or diagnostic information to the supplied output stream.
     */
    public void print(PrintStream out) {
        out.println();
        out.println("__ Working copy (the original submissions are never changed) __");
        out.println("  " + workingDir);
        for (ValidationEvent event : events) {
            // Ignored junk is not printed here; AutoGradeMenu.runGrader logs it quietly through ErrorReporter.ignored.
            if (event.type() == ValidationEvent.Type.IGNORED_JUNK) continue;
            out.println(event.getLogMessage());
        }
        if (usable) {
            out.println("New: " + created + ", reused from an earlier run: " + reused
                    + ", failed: " + failedCount() + ". Edit files in the working copy if you need to.");
        }
        out.println();
    }
}
